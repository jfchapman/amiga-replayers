/*
 * The version of every library here. This is the only place it's set: the libraries, the CMake package and
 * the wasm builds all take it from here.
 */
#ifndef AMIGA_REPLAYERS_VERSION_H
#define AMIGA_REPLAYERS_VERSION_H

#define AMIGA_REPLAYERS_VERSION_MAJOR 0
#define AMIGA_REPLAYERS_VERSION_MINOR 3
#define AMIGA_REPLAYERS_VERSION_PATCH 0

#define AMIGA_REPLAYERS_STRINGIZE_(x) #x
#define AMIGA_REPLAYERS_STRINGIZE(x) AMIGA_REPLAYERS_STRINGIZE_(x)
#define AMIGA_REPLAYERS_VERSION \
	AMIGA_REPLAYERS_STRINGIZE(AMIGA_REPLAYERS_VERSION_MAJOR) "." \
	AMIGA_REPLAYERS_STRINGIZE(AMIGA_REPLAYERS_VERSION_MINOR) "." \
	AMIGA_REPLAYERS_STRINGIZE(AMIGA_REPLAYERS_VERSION_PATCH)

#endif
